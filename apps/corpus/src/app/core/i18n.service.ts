@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly language = signal<AppLanguage>(this.initialLanguage());

  setLanguage(language: AppLanguage): void {
    this.language.set(language);
    localStorage.setItem('corpus-language', language);
    document.documentElement.lang = language;
  }

  translate(key: string): string {
    const lang = this.language();
    return DICTIONARY[lang][key] ?? DICTIONARY.fr[key] ?? key;
  }

  contentLanguage(): string {
    const lang = this.language();
    return lang === 'fr' ? 'br' : lang;
  }

  private initialLanguage(): AppLanguage {
    const saved = localStorage.getItem('corpus-language');
    if (saved === 'fr' || saved === 'br' || saved === 'en' || saved === 'cy') return saved;
    return 'fr';
  }
}
